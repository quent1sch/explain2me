"""
llm_judge.py

Evaluate model outputs using an external LLM as a judge via the Hugging Face API.

PURPOSE
-------
This module compares explanations generated by a base model and a LoRA-adapted
model using an external LLM for evaluation. This avoids loading a second model
locally and enables lightweight, scalable evaluation.

The evaluation supports side-by-side comparison of the base
model and the LoRA-adapted model to quantify improvements in
explanation quality introduced by the adapter.

Each explanation is scored on:
- faithfulness to the concept
- simplicity for the intended audience
- clarity and structure
- overall quality

Outputs include:
- per-sample scores for base and LoRA outputs
- aggregated mean scores across the dataset

PORTABILITY
-----------
- Uses pathlib for cross-platform compatibility
- Supports .env configuration
- Works in local, Docker, cloud, and Colab environments

USAGE
-----
from evaluation.llm_judge import LLMJudge

judge = LLMJudge(config_path="path/to/config.yaml")
summary = judge.run()
"""

import os
from pathlib import Path
import yaml
import json
from tqdm import tqdm
from huggingface_hub import InferenceClient
from dotenv import load_dotenv

load_dotenv()


class LLMJudge:
    """LLM-as-a-judge evaluation using Hugging Face Inference API."""

    def __init__(self, config_path=None):
        base_dir = Path(__file__).resolve().parent

        # Config
        self.config_path = Path(config_path or os.getenv("CONFIG_PATH", "config.yaml"))
        if not self.config_path.is_absolute():
            self.config_path = base_dir / self.config_path
        self.config_path = self.config_path.resolve()

        with self.config_path.open("r") as f:
            self.config = yaml.safe_load(f)

        # Output directory
        self.eval_dir = Path(os.getenv("EVAL_OUTPUT_DIR", "evaluation/evaluation_results"))
        if not self.eval_dir.is_absolute():
            self.eval_dir = base_dir / self.eval_dir
        self.eval_dir.mkdir(parents=True, exist_ok=True)

        # Files
        self.input_file = self.eval_dir / "generated_outputs.json"
        self.output_scores = self.eval_dir / "judge_scores.json"
        self.output_summary = self.eval_dir / "judge_summary.json"

        # HF client
        hf_token = os.getenv("HF_TOKEN")
        if not hf_token:
            raise ValueError("HF_TOKEN not found in environment variables")

        model_id = self.config["llm_as_a_judge"]["model_id"]

        self.client = InferenceClient(
            model=model_id,
            token=hf_token
        )

    @staticmethod
    def _build_prompt(prompt, reference, output):
        return f"""
                You are evaluating explanations produced by an AI tutor.

                User request:
                {prompt}

                Benchmark explanation:
                {reference}

                Generated explanation:
                {output}

                Score from 1 (poor) to 5 (excellent):

                1. Faithfulness to the concept
                2. Simplicity for the intended user
                3. Clarity and structure
                4. Overall explanation quality

                Return ONLY JSON:

                {{
                "faithfulness": int,
                "simplicity": int,
                "clarity": int,
                "overall": int
                }}
                """

    def _judge_output(self, prompt, reference, output):
        judge_prompt = self._build_prompt(prompt, reference, output)

        result = self.client.chat_completion(
            messages=[{"role": "user", "content": judge_prompt}],
            max_tokens=2048,
            temperature=0.2
        )

        response = result.choices[0].message.content

        try:
            start = response.find("{")
            end = response.rfind("}") + 1
            return json.loads(response[start:end])
        except Exception:
            return {
                "faithfulness": None,
                "simplicity": None,
                "clarity": None,
                "overall": None,
            }

    def run(self):
        """Run full LLM-as-a-judge evaluation."""
        print("Loading generated outputs...")
        with self.input_file.open("r", encoding="utf-8") as f:
            samples = json.load(f)

        results = []

        print("Running LLM judge...")
        for sample in tqdm(samples):

            base_scores = self._judge_output(
                sample["question"],
                sample["reference"],
                sample["base_output"]
            )

            lora_scores = self._judge_output(
                sample["question"],
                sample["reference"],
                sample["lora_output"]
            )

            results.append({
                "base": base_scores,
                "lora": lora_scores
            })

        # Save raw results
        with self.output_scores.open("w", encoding="utf-8") as f:
            json.dump(results, f, indent=2)

        # Summary
        metrics = ["faithfulness", "simplicity", "clarity", "overall"]
        summary = {"base": {}, "lora": {}}

        for m in metrics:
            base_vals = [r["base"][m] for r in results if r["base"][m] is not None]
            lora_vals = [r["lora"][m] for r in results if r["lora"][m] is not None]

            summary["base"][m] = sum(base_vals) / len(base_vals) if base_vals else None
            summary["lora"][m] = sum(lora_vals) / len(lora_vals) if lora_vals else None

        with self.output_summary.open("w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)

        print("\nLLM Judge Evaluation Complete.\n")
        print(json.dumps(summary, indent=2))

        return summary