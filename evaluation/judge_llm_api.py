"""
judge_llm_api.py

Purpose:

Evaluate and compare explanations generated by a base Llama model
and a LoRA adapter using an external LLM as a judge via the
Hugging Face Inference API. This avoids loading a second model
locally, saving GPU memory.

Each explanation is scored on:

1. Faithfulness to the concept
2. Simplicity for the intended user (e.g., kid, student, professional)
3. Clarity and structure
4. Overall explanation quality

The evaluation supports side-by-side comparison of the base
model and the LoRA-adapted model to quantify improvements in
explanation quality introduced by the adapter.

Outputs:

- Raw per-example scores for base and LoRA outputs
- Aggregated mean scores across the test set

This approach provides a decent lightweight, though meaningful, 
pipeline.
"""

from pathlib import Path
import os
import yaml
import json
from tqdm import tqdm
from huggingface_hub import InferenceClient
from dotenv import load_dotenv

# ---------------------------
# ENV / CONFIG
# ---------------------------

load_dotenv()

BASE_DIR = Path(__file__).resolve().parent

# Config path
config_path = Path(os.getenv("CONFIG_PATH"))
if not config_path.is_absolute():
    config_path = BASE_DIR / config_path
config_path = config_path.resolve()

with config_path.open("r") as f:
    config = yaml.safe_load(f)

# Evaluation output directory
eval_dir = Path(os.getenv("EVAL_OUTPUT_DIR", "evaluation/evaluation_results"))
if not eval_dir.is_absolute():
    eval_dir = BASE_DIR / eval_dir
eval_dir = eval_dir.resolve()
eval_dir.mkdir(parents=True, exist_ok=True)

# ---------------------------
# FILE PATHS
# ---------------------------

INPUT_FILE = eval_dir / "generate_outputs.json"
OUTPUT_SCORE = eval_dir / "judge_scores.json"
OUTPUT_SUMMARY = eval_dir / "judge_summary.json"

# Hugging Face token
HF_TOKEN = os.getenv("HF_TOKEN")
if not HF_TOKEN:
    raise ValueError("HF_TOKEN not found in environment variables")

# LLM model for judging
model_id = config["llm_as_a_judge"]["model_id"]

# ---------------------------
# LOAD GENERATED OUTPUTS
# ---------------------------

with INPUT_FILE.open("r", encoding="utf-8") as f:
    samples = json.load(f)

# ---------------------------
# INIT HF INFERENCE CLIENT
# ---------------------------

client = InferenceClient(
    model=model_id,
    token=HF_TOKEN,
)


# ---------------------------
# JUDGE PROMPT
# ---------------------------

def build_prompt(prompt, reference, output):

    return f"""
You are evaluating explanations produced by an AI tutor.

User request:
{prompt}

Benchmark explanation:
{reference}

Generated explanation:
{output}

Score from 1 (poor) to 5 (excellent):

1. Faithfulness to the concept
2. Simplicity for the intended user
3. Clarity and structure
4. Overall explanation quality

Return ONLY JSON:

{{
 "faithfulness": int,
 "simplicity": int,
 "clarity": int,
 "overall": int
}}
"""


def judge_output(prompt, reference, output):

    judge_prompt = build_prompt(prompt, reference, output)

    result = client.chat_completion(
        messages=[{"role": "user", "content": judge_prompt}],
        max_tokens=2048,
        temperature=0.2
    )

    response = result.choices[0].message.content

    try:
        start = response.find("{")
        end = response.rfind("}") + 1
        return json.loads(response[start:end])
    except:
        return {
            "faithfulness": None,
            "simplicity": None,
            "clarity": None,
            "overall": None,
        }


# ---------------------------
# RUN EVALUATION
# ---------------------------

results = []

for sample in tqdm(samples):

    base_scores = judge_output(
        sample["question"],
        sample["reference"],
        sample["base_output"]
    )

    lora_scores = judge_output(
        sample["question"],
        sample["reference"],
        sample["lora_output"]
    )

    results.append({
        "base": base_scores,
        "lora": lora_scores
    })


# ---------------------------
# SAVE RAW RESULTS
# ---------------------------

with OUTPUT_SCORE.open("w", encoding="utf-8") as f:
    json.dump(results, f, indent=2)


# ---------------------------
# SUMMARY METRICS
# ---------------------------

metrics = ["faithfulness", "simplicity", "clarity", "overall"]

summary = {
    "base": {},
    "lora": {}
}

for m in metrics:

    base_vals = [r["base"][m] for r in results if r["base"][m] is not None]
    lora_vals = [r["lora"][m] for r in results if r["lora"][m] is not None]

    summary["base"][m] = sum(base_vals) / len(base_vals) if base_vals else None
    summary["lora"][m] = sum(lora_vals) / len(lora_vals) if lora_vals else None


with OUTPUT_SUMMARY.open("w", encoding="utf-8") as f:
    json.dump(summary, f, indent=2)


print("\nEvaluation complete.\n")
print(json.dumps(summary, indent=2))